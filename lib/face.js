/** face id → `[表情:名字]` 或 `[表情:名字(含义)]`；未知 id 用 `[表情#id]`，空 id 用 `[表情]`。 */
export function faceText(rawId) {
  if (rawId === '' || rawId === null || rawId === undefined) return '[表情]'
  const id = Number(rawId)
  if (!Number.isInteger(id) || id < 0) return '[表情]'
  const name = FACE_NAMES[id]
  if (!name) return `[表情#${id}]`
  const hint = FACE_HINTS[id]
  return hint && hint !== name ? `[表情:${name}(${hint})]` : `[表情:${name}]`
}

/** 表情包（mface）：优先用 market face 的 summary（名字）。 */
export function mfaceText(data = {}) {
  const summary = String(data.summary ?? data.name ?? '').trim()
  return summary ? `[表情包:${summary}]` : '[表情包]'
}
